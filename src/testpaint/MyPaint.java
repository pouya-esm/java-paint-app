    private void paintPanelMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_paintPanelMouseClicked
        switch (curAction) {
            case Draw:
                switch (curShape) {
                    case Line:
                        if (p1 == null) {
                            p1 = new Point(evt.getX(), evt.getY());
                        } else {
                            p2 = new Point(evt.getX(), evt.getY());
                            Line l = new Line(p1, p2, curBorderColor);
                            myArea.addShape(l);
                            p1 = p2 = null;
                        }
                        break;
                    case Rectangle:
                        if (p1 == null) {
                            p1 = new Point(evt.getX(), evt.getY());
                        } else {
                            p2 = new Point(evt.getX(), evt.getY());
                            Rectangle r = new Rectangle(p1, p2, curBorderColor, curFillColor);
                            r.isFilled = chbIsFill.isSelected();
                            myArea.addShape(r);

                            p1 = p2 = null;
                        }
                        break;
                    case Circle:
                        if (p1 == null) {
                            p1 = new Point(evt.getX(), evt.getY());
                        } else {
                            p2 = new Point(evt.getX(), evt.getY());
                            Circle c = new Circle(p1, (int) p1.distance(p2), curBorderColor, curFillColor);
                            c.isFilled = chbIsFill.isSelected();
                            myArea.addShape(c);

                            p1 = p2 = null;
                        }
                        break;
                    case Square:
                        if (p1 == null) {
                            p1 = new Point(evt.getX(), evt.getY());
                        } else {
                            p2 = new Point(evt.getX(), evt.getY());
                            // the square starts at the top-left of the two clicks
                            // and its edge is the larger of the two distances
                            int edge = Math.max(Math.abs(p2.getX() - p1.getX()), Math.abs(p2.getY() - p1.getY()));
                            Point topLeft = new Point(Math.min(p1.getX(), p2.getX()), Math.min(p1.getY(), p2.getY()));
                            Square sq = new Square(topLeft, edge, curBorderColor, curFillColor);
                            sq.isFilled = chbIsFill.isSelected();
                            myArea.addShape(sq);
                            p1 = p2 = p3 = null;
                        }
                        break;
                    case Ellipse:
                        // click 1: center, click 2: one radius, click 3: the other radius
                        if (p1 == null) {
                            p1 = new Point(evt.getX(), evt.getY());
                        } else if (p2 == null) {
                            p2 = new Point(evt.getX(), evt.getY());
                        } else {
                            p3 = new Point(evt.getX(), evt.getY());
                            Ellipse e;
                            if (Math.abs(p2.getY() - p1.getY()) > Math.abs(p3.getY() - p1.getY()))
                                e = new Ellipse(p1, Math.abs(p1.getX() - p3.getX()), Math.abs(p1.getY() - p2.getY()), curBorderColor, curFillColor);
                            else
                                e = new Ellipse(p1, Math.abs(p1.getX() - p2.getX()), Math.abs(p1.getY() - p3.getY()), curBorderColor, curFillColor);
                            e.isFilled = chbIsFill.isSelected();
                            myArea.addShape(e);
                            p1 = p2 = p3 = null;
                        }
                        break;
                    case Triangle:
                        if (p1 == null) {
                            p1 = new Point(evt.getX(), evt.getY());
                        } else if (p2 == null) {
                            p2 = new Point(evt.getX(), evt.getY());
                        } else {
                            p3 = new Point(evt.getX(), evt.getY());
                            Triangle tr = new Triangle(p1, p2, p3, curBorderColor, curFillColor);
                            tr.isFilled = chbIsFill.isSelected();
                            myArea.addShape(tr);
                            p1 = p2 = p3 = null;
                        }
                        break;
                    case Polygon:
                        // every click adds a vertex; clicking on the small marker circle
                        // around the first vertex closes the polygon (needs 3+ vertices)
                        Point click = new Point(evt.getX(), evt.getY());
                        if (pArr2 == null) {
                            pArr2 = new Point[]{click};
                            cr = new Circle(click, 5, curBorderColor, Color.cyan);
                            cr.isFilled = true;
                            myArea.addShape(cr);
                        } else if (pArr2.length >= 3 && cr.hit(click)) {
                            myArea.removeShape(myArea.indexOf(cr));
                            Polygon p = new Polygon(pArr2, curBorderColor, curFillColor);
                            p.isFilled = chbIsFill.isSelected();
                            myArea.addShape(p);
                            pArr2 = null;
                            cr = null;
                        } else {
                            pArr2 = Arrays.copyOf(pArr2, pArr2.length + 1);
                            pArr2[pArr2.length - 1] = click;
                            myArea.reDrawAll();
                        }
                        break;
                }
                break;
            case Move:
                if (p1 == null) {
                    p1 = new Point(evt.getX(), evt.getY());
                } else {
                    p2 = new Point(evt.getX(), evt.getY());
                    myArea.moveShape(p1, p2.getX() - p1.getX(), p2.getY() - p1.getY());
                    p1 = p2 = null;
                }
                break;
            case Erase:
                p1 = new Point(evt.getX(), evt.getY());
                Shape s = myArea.getShapeByPoint(p1);
                if (s != null) {
                    myArea.removeShape(myArea.indexOf(s));
                    myArea.reDrawAll();
                    System.out.println(s.name + " deleted.");
                }
                p1 = null;
                break;
            case ZoomIn:
                myArea.scaleShape(new Point(evt.getX(), evt.getY()), 2.0);
                break;
            case ZoomOut:
                myArea.scaleShape(new Point(evt.getX(), evt.getY()), 0.5);
                break;
        }

    }//GEN-LAST:event_paintPanelMouseClicked

    /**
     * Forgets any half-finished drawing (clicked points, polygon in progress).
     * Called whenever another tool is picked.
     */
    private void resetPending() {
        p1 = p2 = p3 = null;
        if (cr != null) {
            myArea.removeShape(myArea.indexOf(cr));
            cr = null;
            myArea.reDrawAll();
        }
        pArr2 = null;
    }

